"""What a rendered read does with the status the page answered.

A 403, a 404, or a 429 is a page the browser reached: its body is what the read exists for,
and the status travels with it. Only a page that says it is a bot filter's refusal is named
as one instead.
"""

from __future__ import annotations

from typing import Any, cast, get_args

import pytest
from playwright.async_api import Error as PlaywrightError

from dlightrag.adapters.agent_browser.driver import network_failure, proxy_page_refusal
from dlightrag.adapters.agent_browser.leased_browser import PlaywrightLeasedBrowser
from dlightrag.engine.answer.agent_browser.contracts import (
    AgentBrowserError,
    AgentBrowserFailure,
)

URL = "https://shop.example/moved"


class _Request:
    def is_navigation_request(self) -> bool:
        return True


class _Response:
    def __init__(self, status: int, page: _Page) -> None:
        self.status = status
        self.frame = page.main_frame
        self.request = _Request()


class _Page:
    """A page that answers one status and serializes to what the test gives it."""

    main_frame = object()

    def __init__(self, status: int | None, body: str) -> None:
        self.url = URL
        self.status = status
        self.body = body
        self.handlers: dict[str, Any] = {}

    def on(self, event: str, handler: Any) -> None:
        self.handlers[event] = handler

    async def goto(self, url: str, **_options: Any) -> None:
        if self.status is not None:
            self.handlers["response"](_Response(self.status, self))

    async def wait_for_load_state(self, state: str, **_options: Any) -> None:
        pass

    async def content(self) -> str:
        return self.body


class _Context:
    def __init__(self, page: _Page) -> None:
        self._page = page

    async def new_page(self) -> _Page:
        return self._page

    async def close(self) -> None:
        pass


class _Browser:
    def __init__(self, page: _Page) -> None:
        self._page = page

    async def new_context(self, **_options: Any) -> _Context:
        return _Context(self._page)

    def is_connected(self) -> bool:
        return True


async def _render(page: _Page) -> Any:
    async def release() -> None:
        pass

    browser = PlaywrightLeasedBrowser(cast(Any, _Browser(page)), release)
    return await browser.render(URL, navigation_timeout=5, settle_timeout=0)


@pytest.mark.parametrize("status", [403, 404, 429, 503])
async def test_a_page_that_answered_an_error_status_is_a_page_with_its_status(status: int) -> None:
    body = "<html><h1>Service unavailable</h1><p>Slow down and try again later.</p></html>"

    rendered = await _render(_Page(status, body))

    # The body is in hand and is what the read answers with; the status is a fact about it.
    assert rendered.status == status
    assert b"Slow down and try again later." in rendered.html


def test_the_egress_boundary_is_named_rather_than_repeated_as_a_chromium_token() -> None:
    refused = network_failure(PlaywrightError("net::ERR_TUNNEL_CONNECTION_FAILED at connect"))

    assert refused is not None and refused.reason == "egress_refused"
    assert "net::ERR" not in refused.public_message
    assert "egress proxy refused the connection" in refused.public_message
    # Any other token is still the token, which is all that is known about that page.
    other = network_failure(PlaywrightError("net::ERR_NAME_NOT_RESOLVED at connect"))
    assert other is not None and other.reason == "navigation_failed"
    assert "net::ERR_NAME_NOT_RESOLVED" in other.public_message


def test_the_proxys_own_error_page_is_its_refusal_and_not_the_sites() -> None:
    squid = (
        b"<html><body><h1>ERROR</h1><pre>Access Denied</pre>Generated by squid/6.6</body></html>"
    )

    assert proxy_page_refusal(403, squid) is not None
    # A 200 that merely mentions the vendor, or a refusal page of the site's own, is neither.
    assert proxy_page_refusal(200, squid) is None
    assert proxy_page_refusal(403, b"<html><body>Access Denied</body></html>") is None


def test_no_reason_left_throws_the_page_away_over_its_status() -> None:
    # The reason came back once already; this is what would have to change for it to return.
    assert "http_status" not in get_args(AgentBrowserFailure)


async def test_a_page_the_egress_proxy_answered_is_named_as_the_deployment_boundary() -> None:
    body = "<html><body><h1>ERROR</h1><pre>Access Denied</pre>Generated by squid/6.6</body></html>"

    with pytest.raises(AgentBrowserError) as refused:
        await _render(_Page(403, body))

    assert refused.value.reason == "egress_refused"
    assert "ports 80 and 443 only" in refused.value.public_message


async def test_a_page_that_says_it_is_a_bot_filter_is_still_a_refusal() -> None:
    body = "<html><head><title>whaleguard block</title></head><body>blocked</body></html>"

    with pytest.raises(AgentBrowserError) as refused:
        await _render(_Page(403, body))

    assert refused.value.reason == "blocked"
    assert "whaleguard" in refused.value.public_message
