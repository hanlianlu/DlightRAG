"""The ``boilerplate`` warning: declarations nobody asked for are flagged, real analysis never is."""

import json
from pathlib import Path

import html_report
import pytest


def hits(markup: str) -> list[str]:
    """The boilerplate warnings of a fragment, as the build prints them."""
    report = html_report._Report(html_report._parse(markup))
    html_report._check_boilerplate(report)
    return report.warnings


