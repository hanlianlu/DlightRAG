        "局限：样本只覆盖 2018–2024 年，未包含服务贸易。",
        "投资扩张与合规风险并行",
        "2021–2023 年逾 100 名奖学金博士生录取不合规",
        "会后发表联合声明，成立绿色转型投资工作组",
