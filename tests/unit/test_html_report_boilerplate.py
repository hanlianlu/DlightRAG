        ("For informational purposes only.", "For informational purposes only", "a disclaimer"),
        ("This is not financial advice.", "not financial advice", "a disclaimer"),
        ("我们重视您的隐私保护。", "隐私保护", "a privacy, compliance or copyright notice"),
        ("隐私政策", "隐私政策", "a privacy, compliance or copyright notice"),
        ("个人信息保护说明", "个人信息保护", "a privacy, compliance or copyright notice"),
        ("This site uses cookies.", "cookies", "a privacy, compliance or copyright notice"),
        ("GDPR compliant", "GDPR", "a privacy, compliance or copyright notice"),
        ("合规声明", "合规声明", "a privacy, compliance or copyright notice"),
        ("Privacy policy", "Privacy policy", "a privacy, compliance or copyright notice"),
        ("版权所有 2024", "版权所有", "a privacy, compliance or copyright notice"),
        ("© 2024 Example", "©", "a privacy, compliance or copyright notice"),
        (
            "All rights reserved.",
            "All rights reserved",
            "a privacy, compliance or copyright notice",
        ),
        ("生成时间：2024-12-31", "生成时间", "a footer credit"),
