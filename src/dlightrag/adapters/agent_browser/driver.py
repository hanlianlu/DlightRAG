"""What a render and an Agent Page share of the Playwright driver."""

from __future__ import annotations

import re

from playwright.async_api import Browser, Page, Playwright, Response
from playwright.async_api import Error as PlaywrightError

from dlightrag.engine.answer.agent_browser.contracts import (
    AgentBrowserError,
    browser_failure,
)

#: The only part of a navigation failure the model reads: Chromium's network error token.
_NETWORK_ERROR = re.compile(r"net::ERR_[A-Z0-9_]+")
#: The tokens a connection our own egress proxy refused arrives as. Chromium reports them the
#: way it reports a site that is down, so the deployment's boundary would read as the site's.
_PROXY_REFUSED = ("net::ERR_TUNNEL_CONNECTION_FAILED", "net::ERR_PROXY_CONNECTION_FAILED")
#: The vendor's own signature on the refusal page the bundled egress proxy (Squid) writes,
#: which for a plain HTTP request is an ordinary 403 the page's own words would not tell
#: apart from a bot filter's.
PROXY_PAGE_MARKER = "generated by squid"
#: Closing a context, or disconnecting a browser, that does not answer must not hold a
#: render, a call, or a Run's settlement open.
CLOSE_SECONDS = 10.0


def milliseconds(seconds: float) -> float:
    """Playwright's timeouts are milliseconds, and 0 would mean no limit at all."""
    return max(1.0, seconds * 1000)


def connection_closed(side: Browser | Playwright) -> bool:
    """Whether the client's connection behind a browser, or behind the driver itself, has closed.

    Playwright offers no public query for this, and this is the one place the adapter reads
    its private state. The client closes a connection when the pipe at its far end ends, and
    keeps the cause in ``_closed_error``. 1.65.1 is pinned (ADR 0032) and tests kill both a
    pool container and the driver, so an upgrade that moves this fails there.
    """
    return side._impl_obj._connection._closed_error is not None


def browser_lost(browser: Browser) -> bool:
    """Whether the browser is gone, whether or not Playwright has announced it yet.

    A closed connection loses every page and fails every call in flight at once, while 1.65
    announces the browser's ``disconnected`` only after the event loop has run everything
    that reacts to the closure, so a call that failed with it still sees a connected browser.
    A page closed on its own leaves the connection open and is not a lost browser.
    """
    return not browser.is_connected() or connection_closed(browser)


def navigation_status(page: Page, response: Response) -> int | None:
    """The status of a response that answers a navigation of the page's main frame, else None."""
    if response.request.is_navigation_request() and response.frame == page.main_frame:
        return response.status
    return None


def starts_download(exc: PlaywrightError) -> bool:
    """Whether a navigation failed because its URL answers with a file, which Chromium downloads."""
    return "Download is starting" in str(exc)


def page_origin(url: str) -> str | None:
    """The origin the web storage of ``url`` belongs to, or None for a page that has none.

    A page the browser opened blank, a ``data:`` URL, or a blob has no origin to carry.
    """
    if not url.startswith(("http://", "https://")):
        return None
    scheme, rest = url.split("://", 1)
    authority = rest.split("/", 1)[0].split("?", 1)[0].split("#", 1)[0]
    return f"{scheme}://{authority}" if authority else None


def network_failure(exc: PlaywrightError) -> AgentBrowserError | None:
    """The failure Chromium's network error token names, or None when the error holds none.

    A token that says a proxy refused the connection is named as this deployment's egress
    boundary rather than repeated raw: nothing about the site is known from it, and a model
    that reads the token retries a site it was never allowed to reach.
    """
    token = _NETWORK_ERROR.search(str(exc))
    if token is None:
        return None
    if token.group() in _PROXY_REFUSED:
        return browser_failure("egress_refused")
    return browser_failure("navigation_failed", detail=token.group())


def proxy_page_refusal(status: int | None, html: bytes) -> AgentBrowserError | None:
    """The failure of a page our own egress proxy answered with, or None when it is not one.

    The proxy refuses a destination on a plain HTTP request with its own error page, which
    is an ordinary 403 with the vendor's signature in it: named here so the deployment's
    policy is not read as the site refusing the browser.
    """
    if status is None or status < 400:
        return None
    if PROXY_PAGE_MARKER not in html.decode("utf-8", errors="replace").casefold():
        return None
    return browser_failure("egress_refused")


async def page_content(page: Page, timeout: float) -> str:
    """The serialized DOM; a navigation in progress is waited out once."""
    try:
        return await page.content()
    except PlaywrightError:
        await page.wait_for_load_state("load", timeout=milliseconds(timeout))
        return await page.content()
