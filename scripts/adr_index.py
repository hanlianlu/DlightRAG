"""Write ``docs/adr/README.md`` from the ADRs themselves.

An index hand-maintained across fifty decisions rots; this one is generated, and
``--check`` fails when the file on disk no longer matches the ADRs, which is what the
test suite runs. Each entry is the ADR's own title and the first sentence of its
status, so the index never states a decision the ADR does not.
"""

from __future__ import annotations

import argparse
import re
import sys
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ADR_DIRECTORY = ROOT / "docs" / "adr"
INDEX_PATH = ADR_DIRECTORY / "README.md"

_DESCRIPTION = "Write docs/adr/README.md from the ADRs themselves."
_NUMBERED = re.compile(r"^(?P<number>\d{4})-")
_TITLE_NUMBER = re.compile(r"^ADR\s+\d{4}\s*[—–-]\s*")
_SENTENCE_END = re.compile(r"(?<=[.!?])(?:[*_`]*)\s")
_MARKDOWN = re.compile(r"[*_`]+")
_HEADING_NUMBER = re.compile(r"^ADR\s+(\d{4})\b")
_MAX_STATUS = 120

HEADER = """# Decision records

One file per decision, numbered in the order they were made. They record why the
product is shaped the way it is; they are not required reading for operating
DlightRAG, which is [Operations](../operations.md) and
[Configuration](../configuration.md).

This index is generated by `scripts/adr_index.py`; run it after adding or editing an
ADR (`uv run python scripts/adr_index.py`), and `make platform-check` fails if it is
stale. Statuses are quoted from each ADR's own `## Status` section.

| ADR | Decision | Status |
|---|---|---|
"""

FOOTER = """
New ADRs take the next number and a kebab-case filename
(`0055-the-thing-is-decided.md`), and open with `# ADR 0055 — the thing is decided`
or a plain title; a `## Status` section is what this index quotes.
"""


@dataclass(frozen=True)
class Entry:
    number: str
    title: str
    status: str
    path: Path


def _section(text: str, heading: str) -> str:
    """The body of one ``## heading`` section, up to the next ``## `` or the end."""
    marker = f"## {heading}"
    if marker not in text:
        return ""
    body = text.split(marker, 1)[1]
    return body.split("\n## ", 1)[0].strip()


_STATUS_LABEL = re.compile(r"^\*{0,2}Status\*{0,2}:\s*(?P<status>.*)$")


def _inline_status(text: str) -> str:
    """The status a record states on one labelled line, wrapping lines joined.

    Most records carry a ``## Status`` section; some state it on a single ``Status: …``
    line, and the newest put the label in bold. The index reads every shape rather than
    forcing the record to change shape.
    """
    lines = text.splitlines()
    for index, line in enumerate(lines):
        match = _STATUS_LABEL.match(line)
        if match is None:
            continue
        paragraph = [match.group("status")]
        for continuation in lines[index + 1 :]:
            if not continuation.strip():
                break
            paragraph.append(continuation.strip())
        return " ".join(part for part in paragraph if part)
    return ""


def _first_sentence(text: str, *, limit: int) -> str:
    """The first sentence of a section, however its lines are wrapped.

    A status is prose: reading only the first line produced truncated claims like
    "Adoption's reach is extended by" in the index, which is worse than no index.
    """
    paragraph = " ".join(line.strip() for line in text.splitlines() if line.strip())
    sentence = _MARKDOWN.sub("", _SENTENCE_END.split(paragraph, maxsplit=1)[0]).strip()
    if len(sentence) > limit:
        sentence = sentence[: limit - 1].rstrip() + "…"
    return sentence or "—"


def entry_for(path: Path) -> Entry:
    text = path.read_text(encoding="utf-8")
    numbered = _NUMBERED.match(path.name)
    if numbered is None:
        msg = f"{path.name} does not start with a four-digit ADR number"
        raise ValueError(msg)
    heading = next((line for line in text.splitlines() if line.startswith("# ")), "")
    numbered_title = _HEADING_NUMBER.match(heading.removeprefix("# "))
    if numbered_title and numbered_title.group(1) != numbered.group("number"):
        raise ValueError(
            f"{path.name} is numbered {numbered.group('number')} but its title says "
            f"{numbered_title.group(1)}"
        )
    title = _TITLE_NUMBER.sub("", heading.removeprefix("# ").strip()).strip()
    # Most ADRs carry a `## Status` section; some state it on one labelled line, plain or
    # bold. The index reads every shape rather than forcing those files to change shape.
    status = _section(text, "Status") or _inline_status(text)
    return Entry(
        number=numbered.group("number"),
        title=title or path.stem,
        status=_first_sentence(status, limit=_MAX_STATUS),
        path=path,
    )


def entries() -> list[Entry]:
    """Every record in the directory, so a misnamed file is an error, not a silence."""
    paths = [path for path in ADR_DIRECTORY.glob("*.md") if path.name != INDEX_PATH.name]
    return [entry_for(path) for path in sorted(paths, key=lambda item: item.name)]


def render(records: list[Entry]) -> str:
    rows = "".join(
        f"| [{record.number}]({record.path.name}) | {record.title} | {record.status} |\n"
        for record in records
    )
    return HEADER + rows + FOOTER


def main() -> int:
    parser = argparse.ArgumentParser(description=_DESCRIPTION)
    parser.add_argument(
        "--check", action="store_true", help="Fail when the index is stale instead of writing"
    )
    arguments = parser.parse_args()

    expected = render(entries())
    if arguments.check:
        current = INDEX_PATH.read_text(encoding="utf-8") if INDEX_PATH.is_file() else ""
        if current != expected:
            print(
                "docs/adr/README.md is stale; run `uv run python scripts/adr_index.py`",
                file=sys.stderr,
            )
            return 1
        print(f"ADR index is current ({len(entries())} entries)")
        return 0

    INDEX_PATH.write_text(expected, encoding="utf-8")
    print(f"wrote {INDEX_PATH.relative_to(ROOT)} ({len(entries())} entries)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
