#!/usr/bin/env bash
# The private eval stack for the interactive-html Skill: a copy of the DlightRAG application with the
# real models and its own PostgreSQL, under the Compose project `dlightrag-eval`.
#
#   stack.sh up            bring the stack up (waits until the API is healthy)
#   stack.sh status        health, the Skills the API reports, mounts, query model
#   stack.sh logs [svc]    follow the logs (svc: dlightrag-api | postgres); FOLLOW=0 TAIL=200 for a snapshot
#   stack.sh restart-api   recreate only the API container (pick up TOOLKIT_DIR / QUERY_MODEL changes)
#   stack.sh down          remove this project's containers, volumes and networks, and nothing else
#   stack.sh init-skills DIR      copy the repo's CURRENT built-in Skills into DIR (a SKILLS_DIR)
#   stack.sh toolkit-init         copy the image's charts toolkit into state/toolkit, from a throwaway container
#                                 of dlightrag:local (never from the live deployment's container)
#
# Environment (all optional):
#   SKILLS_DIR     host directory in the built-in layout (charts/SKILL.md, interactive-html/SKILL.md ...),
#                  bind-mounted read-only over the packaged built-in Skills. Default: this repository's
#                  built-in Skills (src/dlightrag/engine/agent/builtin_skills)
#   TOOLKIT_DIR    host directory overlaying /usr/local/lib/echarts-render (echarts_render.py, ssr.cjs,
#                  theme.json, echarts.min.js, ...). Default: unset (the image's own toolkit)
#   QUERY_MODEL    deepseek (default; config.yaml's query role) | glm (z-ai/glm-5.3-flash via OpenRouter)
#   ENV_FILE       the .env with the model credentials, passed to `docker compose --env-file` only.
#                  Default: <repo>/.env (a git worktree has none: pass the path)
#   CONFIG_FILE    config.yaml. Default: <repo>/config.yaml
#   EVAL_API_PORT  127.0.0.1 port of the API (default 18100); EVAL_PG_PORT of PostgreSQL (default 25433)
#
# Secrets: the .env is only ever handed to Docker with --env-file. This script never reads, prints or
# copies it, and never runs `docker compose config` (which would print substituted secrets).

set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT="dlightrag-eval"
STATE="$HERE/state"
REPO="${REPO:-$(cd "$HERE/../.." && pwd)}"
IMAGE="dlightrag:local"
API_SERVICE="dlightrag-api"

ENV_FILE="${ENV_FILE:-$REPO/.env}"
CONFIG_FILE="${CONFIG_FILE:-$REPO/config.yaml}"
SKILLS_DIR="${SKILLS_DIR:-$REPO/src/dlightrag/engine/agent/builtin_skills}"
TOOLKIT_DIR="${TOOLKIT_DIR:-}"
QUERY_MODEL="${QUERY_MODEL:-deepseek}"
EVAL_API_PORT="${EVAL_API_PORT:-18100}"
EVAL_PG_PORT="${EVAL_PG_PORT:-25433}"
MOUNTS_FILE="$STATE/compose.mounts.yaml"

die() { echo "stack.sh: $*" >&2; exit 1; }
abspath() { (cd "$1" 2>/dev/null && pwd -P) || die "directory not found: $1"; }

# The Compose files for the current environment; sets COMPOSE_FILES (an array).
select_files() {
  COMPOSE_FILES=(-f "$HERE/compose.eval.yaml")
  case "$QUERY_MODEL" in
    deepseek) ;;
    glm) COMPOSE_FILES+=(-f "$HERE/models/glm.yaml") ;;
    *) die "QUERY_MODEL must be deepseek or glm, not '$QUERY_MODEL'" ;;
  esac
  if [ -n "$TOOLKIT_DIR" ]; then
    COMPOSE_FILES+=(-f "$MOUNTS_FILE")
  fi
}

compose() {
  [ -f "$ENV_FILE" ] || die "ENV_FILE not found: $ENV_FILE"
  [ -f "$CONFIG_FILE" ] || die "CONFIG_FILE not found: $CONFIG_FILE"
  select_files
  SKILLS_DIR="$SKILLS_DIR" CONFIG_FILE="$CONFIG_FILE" EVAL_API_PORT="$EVAL_API_PORT" \
    EVAL_PG_PORT="$EVAL_PG_PORT" \
    docker compose -p "$PROJECT" --project-directory "$HERE" --env-file "$ENV_FILE" \
    "${COMPOSE_FILES[@]}" "$@"
}

prepare_skills_dir() {
  [ -d "$SKILLS_DIR" ] || die "SKILLS_DIR is not a directory: $SKILLS_DIR (stack.sh init-skills DIR creates one from the repo)"
  SKILLS_DIR="$(abspath "$SKILLS_DIR")"
  local found
  found="$(find "$SKILLS_DIR" -mindepth 2 -maxdepth 2 -name SKILL.md | wc -l | tr -d ' ')"
  [ "$found" -gt 0 ] || die "SKILLS_DIR holds no <name>/SKILL.md: $SKILLS_DIR"
  # The mount replaces the packaged `dlightrag.engine.agent.builtin_skills` package directory, so the
  # package marker has to be there too.
  if [ ! -f "$SKILLS_DIR/__init__.py" ]; then
    cp "$REPO/src/dlightrag/engine/agent/builtin_skills/__init__.py" "$SKILLS_DIR/__init__.py"
    echo "stack.sh: copied the package marker __init__.py into $SKILLS_DIR"
  fi
}

prepare_mounts() {
  rm -f "$MOUNTS_FILE"
  [ -n "$TOOLKIT_DIR" ] || return 0
  TOOLKIT_DIR="$(abspath "$TOOLKIT_DIR")"
  [ -f "$TOOLKIT_DIR/echarts_render.py" ] || die "TOOLKIT_DIR holds no echarts_render.py: $TOOLKIT_DIR"
  mkdir -p "$STATE"
  {
    echo "# generated by stack.sh from TOOLKIT_DIR; do not edit"
    echo "services:"
    echo "  $API_SERVICE:"
    echo "    volumes:"
    echo "      - type: bind"
    echo "        source: $TOOLKIT_DIR"
    echo "        target: /usr/local/lib/echarts-render"
    echo "        read_only: true"
    echo "        bind:"
    echo "          create_host_path: false"
  } > "$MOUNTS_FILE"
}

api_url() { echo "http://127.0.0.1:${EVAL_API_PORT}"; }

# Only the project's own containers are ever listed or touched.
project_containers() {
  docker ps -a --filter "label=com.docker.compose.project=$PROJECT" --format '{{.Names}}'
}

# What the running stack was started with, for evaluate.py's result metadata.
write_stack_info() {
  mkdir -p "$STATE"
  python3 - "$STATE/stack.json" "$QUERY_MODEL" "$SKILLS_DIR" "${TOOLKIT_DIR:-}" "$(api_url)" <<'PY'
import json, sys, time
path, query_model, skills_dir, toolkit_dir, api_url = sys.argv[1:6]
json.dump(
    {
        "query_model_preset": query_model,
        "skills_dir": skills_dir,
        "toolkit_dir": toolkit_dir or None,
        "api_url": api_url,
        "started_at": time.strftime("%Y-%m-%dT%H:%M:%S%z"),
    },
    open(path, "w"),
    indent=2,
)
PY
}

cmd_up() {
  prepare_skills_dir
  prepare_mounts
  echo "stack.sh: project=$PROJECT query_model=$QUERY_MODEL skills=$SKILLS_DIR toolkit=${TOOLKIT_DIR:-image}"
  compose up -d --wait --wait-timeout 240
  write_stack_info
  cmd_status
}

cmd_restart_api() {
  prepare_skills_dir
  prepare_mounts
  echo "stack.sh: recreating $API_SERVICE (query_model=$QUERY_MODEL skills=$SKILLS_DIR toolkit=${TOOLKIT_DIR:-image})"
  compose up -d --no-deps --force-recreate --wait --wait-timeout 240 "$API_SERVICE"
  write_stack_info
  cmd_status
}

cmd_down() {
  # -v removes this project's named volumes; --remove-orphans its leftover containers. Nothing outside
  # the project is named by this command.
  compose down -v --remove-orphans
  local left
  left="$(project_containers)"
  if [ -n "$left" ]; then
    echo "stack.sh: still present after down: $left" >&2
    exit 1
  fi
  rm -f "$MOUNTS_FILE" "$STATE/stack.json"
  echo "stack.sh: $PROJECT is down (containers, volumes and networks removed)"
}

cmd_logs() {
  # Follows by default; FOLLOW=0 prints the last TAIL lines (default 200) and returns.
  if [ "${FOLLOW:-1}" = "0" ]; then
    compose logs --no-color --tail "${TAIL:-200}" "$@"
  else
    compose logs --no-color --tail "${TAIL:-200}" -f "$@"
  fi
}

cmd_status() {
  echo "== containers ($PROJECT)"
  docker ps -a --filter "label=com.docker.compose.project=$PROJECT" \
    --format 'table {{.Names}}\t{{.Image}}\t{{.Status}}\t{{.Ports}}'
  local url
  url="$(api_url)"
  local started_with="$QUERY_MODEL"
  if [ -f "$STATE/stack.json" ]; then
    started_with="$(python3 -c 'import json,sys; print(json.load(open(sys.argv[1])).get("query_model_preset", "?"))' "$STATE/stack.json" 2>/dev/null || echo "$QUERY_MODEL")"
  fi
  echo "== query model preset the running stack was started with: $started_with (what the API answers with is listed below)"
  echo "== mounts of the API container"
  docker inspect "${PROJECT}-${API_SERVICE}-1" \
    --format '{{range .Mounts}}{{.Type}} {{.Source}} -> {{.Destination}} (rw={{.RW}}){{"\n"}}{{end}}' 2>/dev/null \
    | grep -E 'builtin_skills|echarts-render' || echo "(no API container)"
  echo "== GET $url/ready"
  curl -fsS --max-time 5 "$url/ready" 2>&1 || echo "(not reachable)"
  echo
  echo "== GET $url/health (summary)"
  curl -fsS --max-time 5 "$url/health" 2>/dev/null | python3 -c '
import json, sys
try:
    h = json.load(sys.stdin)
except Exception:
    print("(no health payload)"); raise SystemExit
print({k: h.get(k) for k in ("status", "rag_initialized", "service_role")})
print("answering model (health.answer_image_capability.model):", (h.get("answer_image_capability") or {}).get("model"))
' || echo "(not reachable)"
  echo "== GET $url/web/api/skills (what the API reports)"
  curl -fsS --max-time 5 "$url/web/api/skills" 2>/dev/null | python3 -c '
import json, sys
try:
    skills = json.load(sys.stdin)["skills"]
except Exception:
    print("(no skills payload)"); raise SystemExit
for s in skills:
    print("  %-18s %-8s %s" % (s["name"], s["source"], s["description"][:90]))
' || echo "(not reachable)"
}

cmd_init_skills() {
  local target="${1:-}"
  [ -n "$target" ] || die "usage: stack.sh init-skills DIR"
  [ ! -e "$target" ] || [ -z "$(ls -A "$target" 2>/dev/null)" ] || die "DIR exists and is not empty: $target"
  mkdir -p "$target"
  cp -R "$REPO/src/dlightrag/engine/agent/builtin_skills/." "$target/"
  # Without bytecode caches: the mount is read-only and the image's own are not part of it.
  find "$target" -name __pycache__ -prune -exec rm -rf {} +
  echo "stack.sh: copied the repo's built-in Skills into $target:"
  ls "$target"
}

cmd_toolkit_init() {
  local target="$STATE/toolkit"
  if [ -n "$(ls -A "$target" 2>/dev/null)" ]; then
    die "$target already holds a toolkit copy (remove the directory deliberately to repeat)"
  fi
  mkdir -p "$target"
  # A container that is created and never started, from the image: the running deployment is not read.
  local copy
  copy="$(docker create "$IMAGE")"
  docker cp "$copy:/usr/local/lib/echarts-render/." "$target/"
  docker rm "$copy" > /dev/null
  ls -la "$target"
}

case "${1:-}" in
  up) cmd_up ;;
  down) cmd_down ;;
  status) cmd_status ;;
  logs) shift; cmd_logs "$@" ;;
  restart-api) cmd_restart_api ;;
  init-skills) shift; cmd_init_skills "$@" ;;
  toolkit-init) cmd_toolkit_init ;;
  *) sed -n '2,25p' "$0"; exit 2 ;;
esac
