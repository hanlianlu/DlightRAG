failures = []
for text, expected in POSITIVE:
    got = {h["pattern"] for h in boilerplate.scan_text(text) if h["confidence"] == "high"}
    missing = expected - got
    if missing:
        failures.append(f"MISS {text!r}: expected {sorted(missing)} got {sorted(got)}")
for text in NEGATIVE:
    got = [h for h in boilerplate.scan_text(text) if h["confidence"] == "high"]
    if got:
        failures.append(f"FALSE HIT {text!r}: {[(h['pattern'], h['phrase']) for h in got]}")
soft = boilerplate.scan_text("本报告由三部分组成")
check(soft and all(h["confidence"] == "soft" for h in soft), soft)
hard = boilerplate.scan_text("本报告由 AI 生成")
check(any(h["confidence"] == "high" for h in hard), hard)
print(f"{len(POSITIVE)} positive and {len(NEGATIVE)} negative samples")
if failures:
    print("\n".join(failures))
